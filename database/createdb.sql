-- A transação garante que o script roda inteiro ou não roda nada:
-- se der erro no meio, o banco volta ao estado anterior.
BEGIN;

-- ---------------------------------------------------------------------
-- Remoção das tabelas antigas
-- A ordem é a inversa da criação: primeiro quem depende (tem FK),
-- depois quem é referenciado.
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS item_venda;
DROP TABLE IF EXISTS venda;
DROP TABLE IF EXISTS produto;
DROP TABLE IF EXISTS categoria;
DROP TABLE IF EXISTS usuario;

-- ---------------------------------------------------------------------
-- Usuário (clientes e administradores)
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
                         id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome      VARCHAR(150) NOT NULL,
                         login     VARCHAR(50)  NOT NULL UNIQUE,
    -- hash BCrypt: tem sempre 60 caracteres, com salt e custo embutidos
                         senha     VARCHAR(60)  NOT NULL,
                         email     VARCHAR(150) NOT NULL UNIQUE,
    -- pode ser NULL porque a exclusão lógica apaga o endereço (LGPD);
    -- a obrigatoriedade para contas ativas é garantida pelo ValidadorUsuario
                         endereco  VARCHAR(255),
                         admin     BOOLEAN      NOT NULL DEFAULT FALSE,
                         ativo     BOOLEAN      NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- Categoria
-- ---------------------------------------------------------------------
CREATE TABLE categoria (
                           id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           nome  VARCHAR(100) NOT NULL
);

-- Nome único sem diferenciar maiúsculas e minúsculas: "Livros" e "livros"
-- contam como o mesmo nome. Um UNIQUE comum na coluna diferenciaria os dois.
CREATE UNIQUE INDEX uk_categoria_nome ON categoria (LOWER(nome));

-- ---------------------------------------------------------------------
-- Produto
-- ---------------------------------------------------------------------
CREATE TABLE produto (
                         id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         descricao     VARCHAR(255)  NOT NULL,
                         preco         NUMERIC(10,2) NOT NULL CHECK (preco >= 0),
                         quantidade    INTEGER       NOT NULL DEFAULT 0 CHECK (quantidade >= 0),
    -- caminho relativo à pasta webapp, por exemplo: img/produtos/fone.jpg
                         foto          VARCHAR(255),
    -- RESTRICT: não deixa apagar uma categoria que ainda tem produtos
                         categoria_id  INTEGER       NOT NULL
                             REFERENCES categoria (id) ON DELETE RESTRICT,
    -- exclusão lógica: um produto que já foi vendido não pode sair do banco
    -- (item_venda depende dele), então ele é só escondido da loja
                         ativo         BOOLEAN       NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- Venda (relacionamento Realiza: Usuário 1:N Venda)
-- ---------------------------------------------------------------------
CREATE TABLE venda (
                       id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       data_hora   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- RESTRICT: o usuário nunca é apagado de fato (exclusão lógica)
                       usuario_id  INTEGER   NOT NULL
                           REFERENCES usuario (id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- Item da venda (relacionamento Possui: Venda N:N Produto)
-- O preço é o do momento da venda, e não o preço atual do produto.
-- ---------------------------------------------------------------------
CREATE TABLE item_venda (
                            venda_id    INTEGER       NOT NULL
                                REFERENCES venda (id) ON DELETE CASCADE,
                            produto_id  INTEGER       NOT NULL
                                REFERENCES produto (id) ON DELETE RESTRICT,
                            quantidade  INTEGER       NOT NULL CHECK (quantidade >= 1),
                            preco       NUMERIC(10,2) NOT NULL CHECK (preco >= 0),
    -- o mesmo produto aparece no máximo uma vez por venda
                            PRIMARY KEY (venda_id, produto_id)
);

-- ---------------------------------------------------------------------
-- Índices nas chaves estrangeiras
-- O PostgreSQL cria índice para PRIMARY KEY e UNIQUE automaticamente,
-- mas não para FOREIGN KEY. Eles aceleram os JOINs e as buscas por FK.
-- item_venda(venda_id) já é coberto pela PK (é a primeira coluna dela).
-- ---------------------------------------------------------------------
CREATE INDEX idx_produto_categoria  ON produto (categoria_id);
CREATE INDEX idx_venda_usuario      ON venda (usuario_id);
CREATE INDEX idx_item_venda_produto ON item_venda (produto_id);

