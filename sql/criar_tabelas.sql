-- Apaga as tabelas antigas, das dependentes para as independentes.
-- O CASCADE remove junto as FKs e índices ligados a elas.
DROP TABLE IF EXISTS item_venda CASCADE;
DROP TABLE IF EXISTS venda      CASCADE;
DROP TABLE IF EXISTS produto    CASCADE;
DROP TABLE IF EXISTS categoria  CASCADE;
DROP TABLE IF EXISTS usuario    CASCADE;

-- ---------------------------------------------------------------------
-- USUARIO: clientes e admins na mesma tabela, diferenciados por admin.
-- Nunca é apagado de fato: a exclusão é lógica (ativo = false) e os
-- dados pessoais são anonimizados, preservando o histórico de vendas.
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    -- IDENTITY gera o id sozinho; o DAO recupera com getGeneratedKeys()
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(100) NOT NULL,
    -- 3 a 50 caracteres (validado no ValidadorUsuario)
    login    VARCHAR(50)  NOT NULL UNIQUE,
    -- Texto puro nesta fase; 255 já comporta um hash BCrypt no futuro
    senha    VARCHAR(255) NOT NULL,
    -- Sempre gravado em minúsculas (normalizarEmail)
    email    VARCHAR(255) NOT NULL UNIQUE,
    -- Obrigatório no cadastro, mas aceita NULL porque é apagado
    -- na anonimização da conta excluída
    endereco VARCHAR(255),
    admin    BOOLEAN NOT NULL DEFAULT FALSE,
    ativo    BOOLEAN NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- CATEGORIA
-- ---------------------------------------------------------------------
CREATE TABLE categoria (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL
);

-- ---------------------------------------------------------------------
-- PRODUTO: Categoria 1:N Produto
-- ---------------------------------------------------------------------
CREATE TABLE produto (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- O MER não tem nome; a vitrine usa a descrição como título
    descricao    VARCHAR(255)  NOT NULL,
    -- NUMERIC evita erros de arredondamento; vira BigDecimal no Java
    preco        NUMERIC(10,2) NOT NULL CHECK (preco >= 0),
    -- Estoque; a vitrine só mostra produtos com quantidade > 0
    quantidade   INTEGER       NOT NULL DEFAULT 0 CHECK (quantidade >= 0),
    -- Caminho relativo à pasta webapp, ex.: img/produtos/fone.jpg
    -- A JSP monta ${raiz}/${produto.foto}; NULL mostra "Sem foto"
    foto         VARCHAR(255),
    -- RESTRICT: não deixa apagar uma categoria que ainda tem produtos
    categoria_id INTEGER NOT NULL
                 REFERENCES categoria (id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- VENDA: Usuário 1:N Venda (Realiza)
-- ---------------------------------------------------------------------
CREATE TABLE venda (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- TIMESTAMP vira LocalDateTime no Java
    data_hora  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_id INTEGER NOT NULL
               REFERENCES usuario (id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- ITEM_VENDA: o relacionamento N:N Venda x Produto (Possui) virou tabela.
-- Guarda o preço do momento da venda, que não muda se o produto mudar.
-- ---------------------------------------------------------------------
CREATE TABLE item_venda (
    -- CASCADE: apagar a venda apaga seus itens junto
    venda_id   INTEGER NOT NULL
               REFERENCES venda (id) ON DELETE CASCADE,
    -- RESTRICT: não deixa apagar um produto que já foi vendido
    produto_id INTEGER NOT NULL
               REFERENCES produto (id) ON DELETE RESTRICT,
    preco      NUMERIC(10,2) NOT NULL CHECK (preco >= 0),
    quantidade INTEGER       NOT NULL CHECK (quantidade >= 1),
    -- Chave composta: o mesmo produto aparece uma vez por venda
    -- (adicionarItem() soma a quantidade quando ele se repete)
    PRIMARY KEY (venda_id, produto_id)
);

-- ---------------------------------------------------------------------
-- Índices nas FKs, para acelerar os JOINs e as buscas por relacionamento.
-- item_venda(venda_id) não precisa: já é a 1ª coluna da chave primária.
-- ---------------------------------------------------------------------
CREATE INDEX idx_produto_categoria  ON produto (categoria_id);
CREATE INDEX idx_venda_usuario      ON venda (usuario_id);
CREATE INDEX idx_item_venda_produto ON item_venda (produto_id);

